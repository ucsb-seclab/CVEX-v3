#!/usr/bin/env python3
"""Regenerate stats.tex (the numbers quoted in the report) from the CVEX v3 corpus.

A record counts as functional when it carries .cvex-lock, i.e. tools/cvex_run.py
built and ran it and the verdict was a success. Run this before building the PDF
so the report matches the corpus:  python3 gen_stats.py
"""
import collections, glob, json, os
from pathlib import Path

HERE = Path(__file__).resolve().parent
CVEX = HERE.parent.parent
RECS = CVEX / "CVEX-records"
QUAR = CVEX / "CVEX_v3-unreproduced"

quarantined = {p.name for p in QUAR.glob("CVE-*")} if QUAR.exists() else set()
records = sorted(p for p in RECS.glob("CVE-*") if p.is_dir() and p.name not in quarantined)
locked = [p for p in records if (p / ".cvex-lock").exists()]

crit = collections.Counter()
chan = collections.Counter()
genie, migrated = [], []
cwes, projects = set(), set()
pcap_bytes = sys_bytes = 0
for p in locked:
    v = json.loads((p / "dataset" / "verdict.json").read_text())
    crit[v["criterion"]] += 1
    chan[v["channel"]] += 1
    info = p / "_source" / "cve_info.json"
    if info.exists():
        genie.append(p)
        j = json.loads(info.read_text())
        cwes.update(c["id"] for c in j.get("cwe", []) if c.get("id", "").startswith("CWE-"))
        projects.add(j.get("repo_path", "").strip("/").rsplit("-", 1)[0])
    else:
        migrated.append(p)
    for f in (p / "dataset").glob("*/*"):
        if f.suffix == ".pcap":
            pcap_bytes += f.stat().st_size
        elif f.name.endswith(".syscalls.log"):
            sys_bytes += f.stat().st_size

genie_scaffolds = sum(1 for p in records if (p / "_source" / "cve_info.json").exists())

macros = {
    "NumRecords": len(records),
    "NumFunctional": len(locked),
    "NumScaffolds": len(records) - len(locked),
    "NumQuarantined": len(quarantined),
    "NumGenieScaffolds": genie_scaffolds,
    "NumGenieFunctional": len(genie),
    "NumMigratedFunctional": len(migrated),
    "NumFlag": crit["flag"],
    "NumVerifier": crit["verifier"],
    "NumCrash": crit["crash"],
    "NumChanStdout": chan["stdout"],
    "NumChanNetwork": chan["network"],
    "NumGenieCWEs": len(cwes),
    "NumGenieProjects": len(projects),
    "PcapMiB": f"{pcap_bytes / 2**20:.1f}",
    "SyscallMiB": f"{sys_bytes / 2**20:.0f}",
}
out = ["% Generated by gen_stats.py from CVEX_v3-records -- do not edit by hand."]
out += [f"\\newcommand{{\\{k}}}{{{v}\\xspace}}" for k, v in macros.items()]
(HERE / "stats.tex").write_text("\n".join(out) + "\n")
for k, v in macros.items():
    print(f"{k:24s} {v}")
