#!/usr/bin/env python3
"""
genie_replay.py -- turn CVE-Genie's agent logs into a replayable environment setup.

CVE-Genie's repo_builder and exploiter agents build the environment interactively:
they write helper files (demo servers, go.mod's, configs, PoC inputs), install
packages, compile, and start background services. None of that is in the upstream
source zip, yet verifier.py assumes it. This tool extracts the agents' tool calls,
in order, from

  cve-genie/results/reproduced_cves/<CVE>/conversations/repo_builder_setup_logs.txt
  cve-genie/results/reproduced_cves/<CVE>/conversations/exploiter_logs.txt

and writes, into <record>/target/setup/:

  replay.sh  -- run at image BUILD time from the repo root: every write_to_file
                (exact content, base64) and every foreground execute_linux_command,
                in the agents' order, each in its own subshell, time-limited and
                failure-tolerant (the agents worked by trial and error).
  start.sh   -- run at container START (before benign/attack): the agents'
                environment variables and background commands (servers etc.).
  env.sh     -- the agents' set_environment_variable calls (sourced by both).

Usage: genie_replay.py <CVE> [<CVE> ...] | genie_replay.py --list <file>
"""
import base64, json, re, shlex, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECS = ROOT / "CVEX-records"
GENIE = ROOT / "cve-genie" / "results" / "reproduced_cves"
LOGS = ("repo_builder_setup_logs.txt", "exploiter_logs.txt")
CALL = re.compile(r'^- TOOL CALL \d+: """(\w+)\((.*)\)"""\s*$')
FG_TIMEOUT = 300   # seconds per foreground command (a server run in the foreground)

def calls(cve):
    for log in LOGS:
        p = GENIE / cve / "conversations" / log
        if not p.exists():
            continue
        for line in p.read_text(errors="replace").splitlines():
            mo = CALL.match(line)
            if not mo:
                continue
            try:
                args = json.loads(mo.group(2))
            except json.JSONDecodeError:
                continue
            yield log, mo.group(1), args

def is_background(cmd, args):
    return bool(args.get("background")) or re.search(r"(^|[^&])&\s*$", cmd.strip()) is not None

def generate(cve):
    rec = RECS / cve
    if not rec.exists():
        return "missing"
    setup = rec / "target" / "setup"
    setup.mkdir(parents=True, exist_ok=True)
    rp = ["#!/bin/bash", f"# Replay of CVE-Genie agent setup for {cve} (generated by tools/genie_replay.py).",
          "# Runs from the repo root at image build time; every step is failure-tolerant.",
          ". /setup/env.sh", "R=$(pwd)", "step() { echo \"### $*\"; }"]
    st = ["#!/bin/bash", f"# Background services the CVE-Genie agents left running for {cve}.",
          ". /setup/env.sh", f"cd {shlex.quote('/work')} && cd \"$(cat /setup/repo_dir)\""]
    env = ["# environment variables set by the CVE-Genie agents"]
    n = {"write": 0, "fg": 0, "bg": 0, "env": 0}
    for log, fn, a in calls(cve):
        if fn == "write_to_file" and "filename" in a:
            name = a["filename"]
            if Path(name).name in ("exploit.py", "verifier.py") and "/" not in name:
                continue   # the final versions are COPY'd on top
            b64 = base64.b64encode(a.get("content", "").encode()).decode()
            rp += [f"step write {shlex.quote(name)}",
                   f"( cd \"$R\"; F=\"{name}\"; mkdir -p \"$(dirname \"$F\")\"; "
                   f"echo {b64} | base64 -d > \"$F\" ) || true"]
            n["write"] += 1
        elif fn == "execute_linux_command" and a.get("command"):
            cmd = a["command"]
            if is_background(cmd, a):
                c = re.sub(r"&\s*$", "", cmd.strip())
                st.append(f"( cd \"$(cat /setup/repo_dir)\"; nohup bash -c {shlex.quote(c)} >>/tmp/cvex_bg.log 2>&1 & )")
                rp += [f"step bg {shlex.quote(c[:120])}",
                       f"( cd \"$R\"; timeout 60 bash -c {shlex.quote(c)} ) </dev/null >/dev/null 2>&1 || true"]
                n["bg"] += 1
            else:
                rp += [f"step run {shlex.quote(cmd[:120])}",
                       f"( cd \"$R\"; timeout {FG_TIMEOUT} bash -c {shlex.quote(cmd)} ) </dev/null 2>&1 | tail -20 || true"]
                n["fg"] += 1
        elif fn == "set_environment_variable":
            k = a.get("key") or a.get("name") or a.get("variable")
            v = a.get("value", "")
            if k and re.fullmatch(r"[A-Za-z_]\w*", k):
                env.append(f"export {k}={shlex.quote(str(v))}")
                n["env"] += 1
    rp.append("true")
    st += ["sleep 5", "true"]
    (setup / "replay.sh").write_text("\n".join(rp) + "\n")
    (setup / "start.sh").write_text("\n".join(st) + "\n")
    (setup / "env.sh").write_text("\n".join(env) + "\n")
    for f in ("replay.sh", "start.sh", "env.sh"):
        (setup / f).chmod(0o755)
    return n

def main():
    a = sys.argv[1:]
    if a[:1] == ["--list"]:
        a = [l.split()[0] for l in Path(a[1]).read_text().splitlines() if l.strip()]
    if not a:
        print(__doc__); sys.exit(1)
    for cve in a:
        print(cve, generate(cve))

if __name__ == "__main__":
    main()
